const dictionaries = { en, mr, hi };
export const translate = (language: Language, key: TextKey) => dictionaries[language][key];
export const errorKey = (code: string): TextKey =>
  Object.prototype.hasOwnProperty.call(en, code) ? code as TextKey : 'SERVER_ERROR';
export const money = (value: number | string) =>
  new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', maximumFractionDigits: 0 }).format(Number(value));
export const dateTime = (value: string, language: Language) =>
  new Intl.DateTimeFormat(`${language}-IN`, {
    timeZone: 'Asia/Kolkata', numberingSystem: 'latn',
    day: '2-digit', month: 'short', hour: '2-digit', minute: '2-digit',
  }).format(new Date(value));
